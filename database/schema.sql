create extension if not exists pgcrypto;

create table if not exists public.user_profiles (
    id uuid primary key references auth.users(id) on delete cascade,
    name varchar(120) not null,
    surname varchar(120) not null default '',
    email varchar(320) not null unique,
    phone_number varchar(40),
    state varchar(30) not null default 'active',
    created_at timestamptz not null default now()
);

create table if not exists public.roles (
    id smallint generated by default as identity primary key,
    name varchar(40) not null unique
);

create table if not exists public.user_roles (
    user_id uuid not null references public.user_profiles(id) on delete cascade,
    role_id smallint not null references public.roles(id) on delete cascade,
    primary key (user_id, role_id)
);

create table if not exists public.offer_types (
    id smallint generated by default as identity primary key,
    name varchar(10) not null unique,
    unique (id, name),
    check (name in ('sale', 'rent', 'both'))
);

create table if not exists public.house_types (
    id integer generated by default as identity primary key,
    name varchar(80) not null unique
);

create table if not exists public.room_types (
    id integer generated by default as identity primary key,
    name varchar(80) not null unique
);

create table if not exists public.listings (
    id uuid primary key default gen_random_uuid(),
    title varchar(160) not null,
    description text not null default '',
    mode varchar(10) not null,
    status varchar(30) not null default 'draft',
    owner_id uuid not null references public.user_profiles(id),
    prefecture varchar(80),
    city varchar(120),
    location text,
    offer_type_id smallint not null,
    house_type_id integer not null references public.house_types(id),
    sale_price_jpy bigint check (sale_price_jpy is null or sale_price_jpy > 0),
    monthly_rent_jpy bigint check (monthly_rent_jpy is null or monthly_rent_jpy > 0),
    published_at timestamptz,
    construction_year smallint check (construction_year between 1800 and 2100),
    garage boolean not null default false,
    building_size_m2 numeric(10, 2) check (building_size_m2 is null or building_size_m2 > 0),
    land_size_m2 numeric(10, 2) check (land_size_m2 is null or land_size_m2 > 0),
    availability_months integer check (availability_months is null or availability_months >= 0),
    storage_size_m2 numeric(10, 2) check (storage_size_m2 is null or storage_size_m2 > 0),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    foreign key (offer_type_id, mode) references public.offer_types(id, name),
    check (status in ('draft', 'pending_review', 'published', 'archived')),
    check (mode in ('sale', 'rent', 'both')),
    check (mode in ('sale', 'both') or sale_price_jpy is null),
    check (mode in ('rent', 'both') or monthly_rent_jpy is null)
);

create table if not exists public.rooms (
    id uuid primary key default gen_random_uuid(),
    listing_id uuid not null references public.listings(id) on delete cascade,
    room_type_id integer not null references public.room_types(id),
    size_m2 numeric(10, 2) check (size_m2 is null or size_m2 > 0)
);

create table if not exists public.listing_media (
    id uuid primary key default gen_random_uuid(),
    listing_id uuid not null references public.listings(id) on delete cascade,
    storage_path text not null,
    media_type varchar(20) not null default 'image',
    position integer not null default 0 check (position >= 0),
    created_at timestamptz not null default now()
);

create table if not exists public.listing_imports (
    id uuid primary key default gen_random_uuid(),
    user_id uuid references public.user_profiles(id) on delete set null,
    listing_id uuid references public.listings(id) on delete set null,
    source varchar(40) not null default 'instagram',
    source_account_id varchar(120) not null,
    source_post_id varchar(120) not null,
    status varchar(30) not null default 'pending_review',
    raw_payload jsonb,
    created_at timestamptz not null default now(),
    unique (source, source_account_id, source_post_id),
    check (status in ('pending_review', 'approved', 'rejected', 'imported'))
);

create table if not exists public.listing_import_media (
    id uuid primary key default gen_random_uuid(),
    import_id uuid not null references public.listing_imports(id) on delete cascade,
    storage_path text not null unique,
    media_type varchar(20) not null default 'image',
    source_url text,
    position integer not null default 0 check (position >= 0),
    created_at timestamptz not null default now(),
    unique (import_id, position)
);

create table if not exists public.listing_import_media (
    id uuid primary key default gen_random_uuid(),
    import_id uuid not null references public.listing_imports(id) on delete cascade,
    storage_path text not null unique,
    media_type varchar(20) not null default 'image',
    source_url text,
    position integer not null default 0 check (position >= 0),
    created_at timestamptz not null default now(),
    unique (import_id, position)
);

